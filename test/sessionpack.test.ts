import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const client=await import(new URL('../dist/browser/client/sessionpack.js',import.meta.url).href);
const password='  synthetic café 🔑 fixture  ';
const fixture=await readFile(new URL('./fixtures/session-lantern.synthetic.sessionpack',import.meta.url));
const expected={sessionId:'fixture-session-value',targetIdc:'fixture-region-value',msToken:'fixture-token-value',verifyFp:'fixture-fingerprint-value'};
const payload={service:'tiktok',exportedAt:1,cookies:expected};
const envelope=JSON.parse(fixture.toString());
function file(bytes:Uint8Array=fixture){return {size:bytes.byteLength,arrayBuffer:async()=>Uint8Array.from(bytes).buffer};}
const jsonFile=(value:unknown)=>file(new TextEncoder().encode(JSON.stringify(value)));
const rejected=async(value:ReturnType<typeof file>,secret=password)=>assert.rejects(client.decryptSessionpack(value,secret),{message:client.sessionpackError});

// Generated by Session Lantern's Rust export-fixture example using synthetic credentials only.
test('Rust exporter fixture decrypts with exact Unicode password and clears owned input buffers',async()=>{
  const owned=Uint8Array.from(fixture);
  const cookies=await client.decryptSessionpack({size:owned.length,arrayBuffer:async()=>owned.buffer},password);
  assert.deepEqual(cookies,expected);assert.ok(owned.every(value=>value===0));
  client.clearSessionCookies(cookies);assert.ok(Object.values(cookies).every(value=>value===''));
  await rejected(file(),password.trim());
  await rejected(file(),password.normalize('NFD'));
  await rejected(file(),'incorrect synthetic password');
  const altered=structuredClone(envelope);const bytes=Buffer.from(altered.ciphertext,'base64');bytes[0]^=1;
  altered.ciphertext=bytes.toString('base64');await rejected(jsonFile(altered));
});

test('size and password limits reject before reading or deriving, including unpaired surrogates',async()=>{
  let reads=0;const arrayBuffer=async()=>{reads++;return new ArrayBuffer(0);};
  for(const size of [0,65537,-1,1.5,NaN])await rejected({size,arrayBuffer});
  for(const secret of ['short','x'.repeat(1025),'é'.repeat(513),'🔑'.repeat(11),'long-password-\ud800'])await rejected({size:10,arrayBuffer},secret);
  assert.equal(reads,0);
  await rejected({size:65536,arrayBuffer:async()=>new Uint8Array(65536).buffer});
  await rejected({size:fixture.length-1,arrayBuffer:async()=>Uint8Array.from(fixture).buffer});
  await rejected(file(new Uint8Array([0xff,0xfe])));
  await rejected(file(new TextEncoder().encode('{invalid JSON')));
});

test('exact envelope schemas, algorithms, iterations and canonical padded Base64 are required',async()=>{
  const edits=[
    (x:any)=>{x.extra=true;},(x:any)=>{delete x.ciphertext;},(x:any)=>{x.format='other';},(x:any)=>{x.version=2;},
    (x:any)=>{x.version='1';},(x:any)=>{x.kdf.extra=true;},(x:any)=>{x.kdf.name='PBKDF2';},
    (x:any)=>{x.kdf.iterations=600001;},(x:any)=>{x.kdf.iterations=599999;},(x:any)=>{x.kdf.iterations='600000';},
    (x:any)=>{x.cipher.extra=true;},(x:any)=>{x.cipher.name='AES-GCM';},
    (x:any)=>{x.kdf.salt=x.kdf.salt.slice(0,-2);},(x:any)=>{x.kdf.salt='A'.repeat(21)+'B==';},
    (x:any)=>{x.kdf.salt=Buffer.alloc(15).toString('base64');},(x:any)=>{x.cipher.iv=Buffer.alloc(11).toString('base64');},
    (x:any)=>{x.ciphertext='';},(x:any)=>{x.ciphertext=Buffer.alloc(15).toString('base64');},
    (x:any)=>{x.ciphertext+='\n';},(x:any)=>{x.ciphertext='____';},(x:any)=>{x.ciphertext=null;},
  ];
  let derives=0;const original=crypto.subtle.deriveKey;
  Object.defineProperty(crypto.subtle,'deriveKey',{configurable:true,value:()=>{derives++;throw new Error();}});
  try{
    for(const edit of edits){const candidate=structuredClone(envelope);edit(candidate);await rejected(jsonFile(candidate));}
    for(const candidate of [null,[],{},'text'])await rejected(jsonFile(candidate));
    assert.equal(derives,0);
  }finally{Object.defineProperty(crypto.subtle,'deriveKey',{configurable:true,value:original});}
});

test('authenticated plaintext requires exact payload schema and API cookie bounds',async()=>{
  const salt=crypto.getRandomValues(new Uint8Array(16)),iv=crypto.getRandomValues(new Uint8Array(12));
  const material=await crypto.subtle.importKey('raw',new TextEncoder().encode(password),'PBKDF2',false,['deriveKey']);
  const key=await crypto.subtle.deriveKey({name:'PBKDF2',hash:'SHA-256',salt,iterations:600000},material,{name:'AES-GCM',length:256},false,['encrypt']);
  const encrypt=async(value:unknown,aad='session-lantern:v1')=>{
    const ciphertext=await crypto.subtle.encrypt({name:'AES-GCM',iv,additionalData:new TextEncoder().encode(aad),tagLength:128},key,new TextEncoder().encode(JSON.stringify(value)));
    return jsonFile({...envelope,kdf:{...envelope.kdf,salt:Buffer.from(salt).toString('base64')},cipher:{...envelope.cipher,iv:Buffer.from(iv).toString('base64')},ciphertext:Buffer.from(ciphertext).toString('base64')});
  };
  const edits=[
    (x:any)=>{x.extra=true;},(x:any)=>{x.service='other';},(x:any)=>{delete x.cookies;},
    ...[0,-1,1.5,Number.MAX_SAFE_INTEGER+1,'1'].map(at=>(x:any)=>{x.exportedAt=at;}),
    (x:any)=>{x.cookies.extra='x';},(x:any)=>{delete x.cookies.verifyFp;},(x:any)=>{x.cookies.sessionId=123;},
    (x:any)=>{x.cookies.sessionId='';},(x:any)=>{x.cookies.sessionId='a'.repeat(257);},(x:any)=>{x.cookies.sessionId='bad;cookie';},
    (x:any)=>{x.cookies.targetIdc='a'.repeat(65);},(x:any)=>{x.cookies.targetIdc='a.b';},
    (x:any)=>{x.cookies.msToken='a'.repeat(1025);},(x:any)=>{x.cookies.msToken='a b';},
    (x:any)=>{x.cookies.verifyFp='a'.repeat(201);},(x:any)=>{x.cookies.verifyFp='é';},
    ...Object.keys(expected).map(key=>(x:any)=>{x.cookies[key]+='\n';}),
  ];
  for(const edit of edits){const candidate=structuredClone(payload);edit(candidate);await rejected(await encrypt(candidate));}
  await rejected(await encrypt(payload,'session-lantern:v2'));
  const boundary={sessionId:'a'.repeat(256),targetIdc:'a'.repeat(64),msToken:'=+/-'.repeat(256),verifyFp:'a'.repeat(200)};
  assert.deepEqual(await client.decryptSessionpack(await encrypt({...payload,cookies:boundary}),password),boundary);
});
